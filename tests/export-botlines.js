/**
 * Export botlines.json -> botlines_js.js (browser global for game.js's BotChat).
 * (PHP reads data/botlines.json directly; no PHP export needed anymore.)
 * Run after editing data/botlines.json:  node tests/export-botlines.js
 */
"use strict";
const fs = require("fs");
const path = require("path");

const json = JSON.parse(fs.readFileSync(path.join(__dirname, "..", "data", "botlines.json"), "utf8"));
if (!json.groups || typeof json.groups !== "object") {
  console.error("botlines.json has no groups object");
  process.exit(1);
}

// -- sanity: every group must have at least one non-empty line array ------------
for (const [group, byPers] of Object.entries(json.groups)) {
  const lines = Object.values(byPers).flat();
  if (!lines.length) { console.error(`group '${group}' has no lines`); process.exit(1); }
}

const dataJs =
  `/** AUTO-GENERATED by tests/export-botlines.js — edit data/botlines.json instead. */\n` +
  `window.BOT_LINES = ${JSON.stringify(json.groups, null, 2)};\n`;
fs.writeFileSync(path.join(__dirname, "..", "data", "botlines_js.js"), dataJs, "utf8");

fs.writeFileSync(path.join(__dirname, "..", "data", "botlines_js.js"), dataJs, "utf8");
console.log(`botlines: ${Object.keys(json.groups).length} groups exported to data/botlines_js.js`);
